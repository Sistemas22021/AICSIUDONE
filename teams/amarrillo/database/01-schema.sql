--
-- Nota: la columna geom de 'ubicacion' se define directamente en el CREATE TABLE.
-- Esto evita el error "record new has no field geom" que ocurre cuando la tabla
-- se crea sin esa columna (por ejemplo si Hibernate la crea antes).
-- ============================================================================

-- ============================================================================
-- 1. EXTENSION POSTGIS (imprescindible para la columna geom)
-- ============================================================================
CREATE EXTENSION IF NOT EXISTS postgis;

-- ============================================================================
-- 2. FUNCION DEL TRIGGER: calcula geom a partir de latitud/longitud
-- ============================================================================
CREATE OR REPLACE FUNCTION trigger_ubicacion_set_geom() RETURNS trigger
    LANGUAGE plpgsql
    AS $$
BEGIN
    NEW.geom := ST_SetSRID(ST_MakePoint(NEW.longitud, NEW.latitud), 4326)::geography;
    RETURN NEW;
END;
$$;

