-- ============================================================================
-- 6. TRIGGER DE GEOMETRIA (despues de que la tabla ubicacion existe)
-- ============================================================================
DROP TRIGGER IF EXISTS tr_ubicacion_geom ON ubicacion;
CREATE TRIGGER tr_ubicacion_geom
    BEFORE INSERT OR UPDATE ON ubicacion
    FOR EACH ROW EXECUTE FUNCTION trigger_ubicacion_set_geom();

-- ============================================================================
-- 7. VISTA DEL GRAFO (etiquetas legibles de los vinculos activos)
-- ============================================================================
CREATE OR REPLACE VIEW v_grafo_vinculos AS
 SELECT id AS vinculo_id,
    tipo_origen,
    id_origen,
        CASE tipo_origen
            WHEN 'PERSONA'::text  THEN (SELECT persona.nombre || ' ' || persona.apellido FROM persona WHERE persona.id = v.id_origen)
            WHEN 'VEHICULO'::text THEN (SELECT vehiculo.placa      FROM vehiculo  WHERE vehiculo.id  = v.id_origen)::text
            WHEN 'UBICACION'::text THEN (SELECT ubicacion.direccion FROM ubicacion WHERE ubicacion.id = v.id_origen)::text
            WHEN 'SUCESO'::text   THEN ('Suceso #'::text || id_origen)
            ELSE NULL::text
        END AS label_origen,
    tipo_destino,
    id_destino,
        CASE tipo_destino
            WHEN 'PERSONA'::text  THEN (SELECT persona.nombre || ' ' || persona.apellido FROM persona WHERE persona.id = v.id_destino)
            WHEN 'VEHICULO'::text THEN (SELECT vehiculo.placa      FROM vehiculo  WHERE vehiculo.id  = v.id_destino)::text
            WHEN 'UBICACION'::text THEN (SELECT ubicacion.direccion FROM ubicacion WHERE ubicacion.id = v.id_destino)::text
            WHEN 'SUCESO'::text   THEN ('Suceso #'::text || id_destino)
            ELSE NULL::text
        END AS label_destino,
    regla_detectada,
    score,
    detectado_en
   FROM vinculo v
  WHERE activo = true;

